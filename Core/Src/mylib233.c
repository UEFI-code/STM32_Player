char DbgPrint_Buffer[1024] = {0};
char UART_Recieve_Buffer[1024] = {0};
uint16_t freq_a = 440, freq_b = 880;

void myUART_RxPraser()
{
    if(strcmp(UART_Recieve_Buffer, "Hi") == 0)
    {
        DbgPrint("Hello World\n");
    }
    else if(strncmp(UART_Recieve_Buffer, "set dtmf ", 9) == 0)
    {
        sscanf(UART_Recieve_Buffer + 9, "%hu %hu", &freq_a, &freq_b);
        DbgPrint("Set DTMF frequencies: %hu Hz, %hu Hz\n", freq_a, freq_b);
    }
    else
    {
        DbgPrint("Unknown Command\n");
    }
}

void myUART_RxHandler(UART_HandleTypeDef *huart)
{
    static int i = 0;
    UART_Recieve_Buffer[i] = (char)(huart->Instance->DR & (uint8_t)0xFF);
    if (UART_Recieve_Buffer[i] == '\n')
    {
        UART_Recieve_Buffer[i] = 0; // Set the end of string
        myUART_RxPraser();
        i = 0;
        return;
    }
    i = (i + 1) % sizeof(UART_Recieve_Buffer);
}

void HAL_Delay(uint32_t Delay)
{
    uint32_t tickstart = uwTick;

    /* Add a freq to guarantee minimum wait */
    if (Delay < HAL_MAX_DELAY) Delay += (uint32_t)(uwTickFreq);

    while ((uwTick - tickstart) < Delay)
        asm volatile ("wfi");
}

